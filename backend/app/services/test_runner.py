"""
TestRunner: parses pytest output into structured TestRunResult.

Supports:
- pytest with default terminal output and --tb=short
- pytest with --junit-xml output (preferred when available)
- Graceful fallback when output is truncated or malformed

Does NOT execute code directly. Receives the ExecutionResult from
ExecutionService and parses its stdout/stderr.
"""

from __future__ import annotations

import json
import re
import xml.etree.ElementTree as ET
from datetime import datetime, timezone
from pathlib import Path
from typing import List, Optional

from app.core.logging import get_logger
from app.schemas.execution import (
    CommandStatus,
    ExecutionResult,
    TestOutcome,
    TestResult,
    TestRunResult,
)

log = get_logger(__name__)


class TestRunner:
    """
    Parses test output from an ExecutionResult into a structured TestRunResult.
    """

    def build_pytest_command(
        self,
        test_paths: Optional[List[str]] = None,
        xml_output_path: Optional[str] = None,
        extra_args: Optional[List[str]] = None,
    ) -> List[str]:
        """
        Build a pytest command array safe for sandbox execution.
        No shell interpolation — every element is a separate argument.
        """
        cmd = ["python", "-m", "pytest", "-v", "--tb=short", "--no-header"]
        if xml_output_path:
            cmd += ["--junit-xml", xml_output_path]
        if test_paths:
            for p in test_paths:
                # Validate path — no shell chars
                if any(c in p for c in (";", "&", "|", "`", "$", "<", ">")):
                    log.warning("test_path_skipped_metachar", path=p)
                    continue
                cmd.append(p)
        if extra_args:
            for a in extra_args:
                if any(c in a for c in (";", "&", "|", "`", "$")):
                    continue
                cmd.append(a)
        return cmd

    def parse_execution_result(
        self,
        result: ExecutionResult,
        framework: str = "pytest",
        junit_xml: Optional[str] = None,
    ) -> TestRunResult:
        """
        Convert an ExecutionResult into a TestRunResult.
        Tries JUnit XML first, falls back to stdout parsing.
        """
        run_at = result.finished_at or datetime.now(timezone.utc)
        tests: List[TestResult] = []

        if junit_xml:
            try:
                tests = self._parse_junit_xml(junit_xml)
            except Exception as exc:
                log.warning("junit_parse_failed", error=str(exc))

        if not tests:
            tests = self._parse_pytest_stdout(result.stdout + "\n" + result.stderr)

        passed = sum(1 for t in tests if t.outcome == TestOutcome.passed)
        failed = sum(1 for t in tests if t.outcome == TestOutcome.failed)
        errors = sum(1 for t in tests if t.outcome == TestOutcome.error)
        skipped = sum(1 for t in tests if t.outcome == TestOutcome.skipped)

        # If we got a non-zero exit code but parsed zero tests, add a synthetic error
        if not tests and result.status != CommandStatus.success:
            tests.append(TestResult(
                name="<execution>",
                outcome=TestOutcome.error,
                message=self._extract_error_summary(result.stderr or result.stdout),
            ))
            errors = 1

        return TestRunResult(
            framework=framework,
            command=result.command,
            execution=result,
            tests=tests,
            total=len(tests),
            passed=passed,
            failed=failed,
            errors=errors,
            skipped=skipped,
            run_at=run_at,
        )

    def to_summary_dict(self, run: TestRunResult) -> dict:
        """Compact dict suitable for persistence and prompt building."""
        failing = [
            t.name for t in run.tests
            if t.outcome in (TestOutcome.failed, TestOutcome.error)
        ]
        return {
            "total": run.total,
            "passed": run.passed,
            "failed": run.failed,
            "errors": run.errors,
            "skipped": run.skipped,
            "failing_tests": failing[:50],
            "exit_code": run.execution.exit_code,
            "timed_out": run.execution.timed_out,
            "duration_seconds": run.execution.duration_seconds,
        }

    # ── Parsers ────────────────────────────────────────────────────────────────

    def _parse_junit_xml(self, xml_path: str) -> List[TestResult]:
        """Parse a JUnit XML file generated by pytest --junit-xml."""
        tree = ET.parse(xml_path)
        root = tree.getroot()
        results = []

        # <testsuites> or <testsuite> at root
        suites = root.findall("testsuite") or [root]
        for suite in suites:
            for case in suite.findall("testcase"):
                name = f"{case.get('classname','')}.{case.get('name','')}".strip(".")
                duration = float(case.get("time", 0) or 0)

                failure = case.find("failure")
                error = case.find("error")
                skipped = case.find("skipped")

                if failure is not None:
                    outcome = TestOutcome.failed
                    message = failure.get("message", "") or (failure.text or "")[:500]
                elif error is not None:
                    outcome = TestOutcome.error
                    message = error.get("message", "") or (error.text or "")[:500]
                elif skipped is not None:
                    outcome = TestOutcome.skipped
                    message = skipped.get("message", "")
                else:
                    outcome = TestOutcome.passed
                    message = None

                results.append(TestResult(
                    name=name,
                    outcome=outcome,
                    duration_seconds=duration,
                    message=message,
                ))
        return results

    def _parse_pytest_stdout(self, output: str) -> List[TestResult]:
        """
        Parse pytest's --tb=short terminal output.
        Handles both PASSED/FAILED per-line markers and the summary section.
        """
        results: List[TestResult] = []
        seen: set[str] = set()

        # Pattern: "tests/test_foo.py::test_bar PASSED" or "FAILED"
        line_re = re.compile(
            r"^(.*?::[\w\[\]., -]+)\s+(PASSED|FAILED|ERROR|SKIPPED)",
            re.MULTILINE,
        )

        outcome_map = {
            "PASSED": TestOutcome.passed,
            "FAILED": TestOutcome.failed,
            "ERROR": TestOutcome.error,
            "SKIPPED": TestOutcome.skipped,
        }

        for m in line_re.finditer(output):
            name = m.group(1).strip()
            outcome = outcome_map[m.group(2)]
            if name not in seen:
                seen.add(name)
                results.append(TestResult(name=name, outcome=outcome))

        # If we still have no results, try the summary line:
        # "3 passed, 2 failed in 0.5s" or "5 failed in 1.2s"
        if not results:
            summary_re = re.compile(
                r"(\d+) passed.*?(\d+) failed|(\d+) failed|(\d+) passed",
                re.IGNORECASE,
            )
            m = summary_re.search(output)
            if m:
                passed_n = int(m.group(1) or m.group(4) or 0)
                failed_n = int(m.group(2) or m.group(3) or 0)
                for i in range(passed_n):
                    results.append(TestResult(
                        name=f"<test_{i+1}>",
                        outcome=TestOutcome.passed,
                    ))
                for i in range(failed_n):
                    results.append(TestResult(
                        name=f"<failing_test_{i+1}>",
                        outcome=TestOutcome.failed,
                    ))

        # Extract failure messages for FAILED tests (short tb format)
        if results:
            self._attach_failure_messages(output, results)

        return results

    def classify_failure(self, result: ExecutionResult) -> str:
        """
        Distinguishes application test failure from missing dependencies,
        missing runners, timeout, or infrastructure errors.
        Returns one of:
          'infrastructure_error', 'timeout', 'runner_not_found',
          'missing_dependency', 'test_failure', 'success'
        """
        if result.timed_out or result.status == CommandStatus.timeout:
            return "timeout"
        combined = (result.stderr + "\n" + result.stdout).lower()
        if "docker sandbox is not available" in combined or "missing prerequisite" in combined or "sandbox execution error" in combined:
            return "infrastructure_error"
        # Python runners
        if "no module named pytest" in combined or "pytest: command not found" in combined or "pytest: not found" in combined:
            return "runner_not_found"
        # Jest / npx runners
        if "jest: not found" in combined or "cannot find module 'jest'" in combined or "jest is not recognized" in combined:
            return "runner_not_found"
        if "npx: not found" in combined or "npx is not recognized" in combined:
            return "runner_not_found"
        # Go runner
        if "go: not found" in combined or "go: command not found" in combined:
            return "runner_not_found"
        # Missing dependencies
        if "modulenotfounderror:" in combined or "importerror:" in combined or "no module named" in combined:
            return "missing_dependency"
        if "cannot find module" in combined or "module not found" in combined:
            return "missing_dependency"
        if result.exit_code == 0:
            return "success"
        return "test_failure"

    def parse_error_traces(self, text: str) -> List[dict]:
        """
        Extract structured error traces from output: exception type, message,
        and failing location.
        """
        traces = []
        # Pattern for File "...", line \d+, in ...
        frame_re = re.compile(r'File "([^"]+)", line (\d+), in (\w+)')
        exc_re = re.compile(r"^([A-Z]\w*(?:Error|Exception|Warning)): (.+)$", re.MULTILINE)

        for m in exc_re.finditer(text):
            exc_type = m.group(1)
            exc_msg = m.group(2).strip()
            # Look backwards for the nearest File "...", line X frame
            start_pos = max(0, m.start() - 1000)
            preceding = text[start_pos:m.start()]
            frames = frame_re.findall(preceding)
            failing_file = frames[-1][0] if frames else None
            failing_line = int(frames[-1][1]) if frames else None
            failing_func = frames[-1][2] if frames else None

            traces.append({
                "exception_type": exc_type,
                "message": exc_msg[:300],
                "file_path": failing_file,
                "line_number": failing_line,
                "function": failing_func,
            })
        return traces[:10]

    def _attach_failure_messages(
        self, output: str, results: List[TestResult]
    ) -> None:
        """
        Try to attach a short failure message to FAILED TestResults by
        matching their names against the FAILURES section of the output.
        """
        # FAILURES section: "FAILED tests/test_foo.py::test_bar - message"
        short_fail_re = re.compile(
            r"^FAILED (.*?::[\w\[\]., -]+) - (.+)$", re.MULTILINE
        )
        msg_map: dict[str, str] = {}
        for m in short_fail_re.finditer(output):
            msg_map[m.group(1).strip()] = m.group(2).strip()[:300]

        for result in results:
            if result.outcome == TestOutcome.failed and result.name in msg_map:
                result.message = msg_map[result.name]

    def _extract_error_summary(self, text: str) -> str:
        """Extract a useful short error description from stderr/stdout."""
        if not text:
            return "Unknown execution error"
        # Return the last meaningful non-empty lines
        lines = [l for l in text.splitlines() if l.strip()]
        return "\n".join(lines[-5:])[:500]


class JestTestRunner:
    """Parses Jest JSON output (--json flag) into TestRunResult."""

    def build_jest_command(self, test_paths=None, extra_args=None) -> List[str]:
        """Build npx --yes jest --json command. JSON output goes to stdout."""
        cmd = ["npx", "--yes", "jest", "--json", "--no-coverage"]
        if test_paths:
            for p in test_paths:
                if any(c in p for c in (";", "&", "|", "`", "$", "<", ">")):
                    continue
                cmd.append(p)
        return cmd

    def parse_execution_result(self, result: ExecutionResult, framework: str = "jest") -> TestRunResult:
        """Parse jest --json output from stdout."""
        run_at = result.finished_at or datetime.now(timezone.utc)
        tests: List[TestResult] = []

        # Jest prints JSON to stdout
        try:
            # Find JSON object in stdout (jest may print extra lines before it)
            stdout = result.stdout or ""
            # Find the first '{' for the JSON block
            json_start = stdout.find('{')
            if json_start >= 0:
                data = json.loads(stdout[json_start:])
                tests = self._parse_jest_json(data)
        except (json.JSONDecodeError, KeyError, TypeError):
            # Fallback: parse text output
            tests = self._parse_jest_text(result.stdout + "\n" + result.stderr)

        # Synthetic error if no tests found and non-zero exit
        if not tests and result.status != CommandStatus.success:
            tests.append(TestResult(
                name="<jest-execution>",
                outcome=TestOutcome.error,
                message=self._extract_error_summary(result.stderr or result.stdout),
            ))

        passed = sum(1 for t in tests if t.outcome == TestOutcome.passed)
        failed = sum(1 for t in tests if t.outcome == TestOutcome.failed)
        errors = sum(1 for t in tests if t.outcome == TestOutcome.error)
        skipped = sum(1 for t in tests if t.outcome == TestOutcome.skipped)

        return TestRunResult(
            framework=framework,
            command=result.command,
            execution=result,
            tests=tests,
            total=len(tests),
            passed=passed,
            failed=failed,
            errors=errors,
            skipped=skipped,
            run_at=run_at,
        )

    def to_summary_dict(self, run: TestRunResult) -> dict:
        failing = [t.name for t in run.tests if t.outcome in (TestOutcome.failed, TestOutcome.error)]
        return {
            "total": run.total,
            "passed": run.passed,
            "failed": run.failed,
            "errors": run.errors,
            "skipped": run.skipped,
            "failing_tests": failing[:50],
            "exit_code": run.execution.exit_code,
            "timed_out": run.execution.timed_out,
            "duration_seconds": run.execution.duration_seconds,
        }

    def _parse_jest_json(self, data: dict) -> List[TestResult]:
        results = []
        for suite in data.get("testResults", []):
            for test in suite.get("testResults", []):
                status = test.get("status", "")
                if status == "passed":
                    outcome = TestOutcome.passed
                elif status == "failed":
                    outcome = TestOutcome.failed
                elif status == "pending" or status == "todo":
                    outcome = TestOutcome.skipped
                else:
                    outcome = TestOutcome.error

                full_name = test.get("fullName", test.get("title", "<unknown>"))
                duration = test.get("duration")
                duration_s = duration / 1000.0 if duration else None

                message = None
                if outcome in (TestOutcome.failed, TestOutcome.error):
                    messages = test.get("failureMessages", [])
                    if messages:
                        message = messages[0][:500]

                results.append(TestResult(
                    name=full_name,
                    outcome=outcome,
                    duration_seconds=duration_s,
                    message=message,
                ))
        return results

    def _parse_jest_text(self, output: str) -> List[TestResult]:
        """Fallback: parse Jest's default terminal output."""
        results = []
        seen = set()
        # Pattern: "✓ test name (Xms)" or "✗ test name" or "× test name"
        pass_re = re.compile(r"[✓✔●]\s+(.+?)(?:\s+\(\d+\s*ms\))?$", re.MULTILINE)
        fail_re = re.compile(r"[✗×✕●]\s+(.+?)(?:\s+\(\d+\s*ms\))?$", re.MULTILINE)

        for m in pass_re.finditer(output):
            name = m.group(1).strip()
            if name not in seen:
                seen.add(name)
                results.append(TestResult(name=name, outcome=TestOutcome.passed))

        for m in fail_re.finditer(output):
            name = m.group(1).strip()
            if name not in seen:
                seen.add(name)
                results.append(TestResult(name=name, outcome=TestOutcome.failed))

        return results

    def _extract_error_summary(self, text: str) -> str:
        if not text:
            return "Unknown Jest execution error"
        lines = [l for l in text.splitlines() if l.strip()]
        return "\n".join(lines[-5:])[:500]


class GoTestRunner:
    """Parses go test -json output into TestRunResult."""

    def build_go_test_command(self, test_paths=None, extra_args=None) -> List[str]:
        """go test -json ./..."""
        cmd = ["go", "test", "-json"]
        if test_paths:
            for p in test_paths:
                if any(c in p for c in (";", "&", "|", "`", "$", "<", ">")):
                    continue
                cmd.append(p)
        else:
            cmd.append("./...")
        return cmd

    def parse_execution_result(self, result: ExecutionResult, framework: str = "go_test") -> TestRunResult:
        run_at = result.finished_at or datetime.now(timezone.utc)
        tests: List[TestResult] = []

        try:
            tests = self._parse_go_json_lines(result.stdout or "")
        except Exception:
            pass

        if not tests and result.status != CommandStatus.success:
            tests.append(TestResult(
                name="<go-test-execution>",
                outcome=TestOutcome.error,
                message=(result.stderr or result.stdout or "")[:500],
            ))

        passed = sum(1 for t in tests if t.outcome == TestOutcome.passed)
        failed = sum(1 for t in tests if t.outcome == TestOutcome.failed)
        errors = sum(1 for t in tests if t.outcome == TestOutcome.error)
        skipped = sum(1 for t in tests if t.outcome == TestOutcome.skipped)

        return TestRunResult(
            framework=framework,
            command=result.command,
            execution=result,
            tests=tests,
            total=len(tests),
            passed=passed,
            failed=failed,
            errors=errors,
            skipped=skipped,
            run_at=run_at,
        )

    def _parse_go_json_lines(self, output: str) -> List[TestResult]:
        """Parse NDJSON lines from go test -json."""
        results: dict[str, TestResult] = {}
        for line in output.splitlines():
            line = line.strip()
            if not line or not line.startswith("{"):
                continue
            try:
                event = json.loads(line)
            except json.JSONDecodeError:
                continue
            action = event.get("Action", "")
            test_name = event.get("Test")
            if not test_name:
                continue
            if action == "pass":
                results[test_name] = TestResult(
                    name=test_name,
                    outcome=TestOutcome.passed,
                    duration_seconds=event.get("Elapsed"),
                )
            elif action == "fail":
                results[test_name] = TestResult(
                    name=test_name,
                    outcome=TestOutcome.failed,
                    duration_seconds=event.get("Elapsed"),
                )
            elif action == "skip":
                results[test_name] = TestResult(
                    name=test_name,
                    outcome=TestOutcome.skipped,
                )
        return list(results.values())
